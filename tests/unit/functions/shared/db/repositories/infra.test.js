import { describe, it, expect } from 'vitest'
import { fakeDb } from '../../../../../helpers/mocks.js'
import * as jobs from '../../../../../../functions/shared/db/repositories/jobs.js'
import * as schedules from '../../../../../../functions/shared/db/repositories/schedules.js'
import * as auth from '../../../../../../functions/shared/db/repositories/auth.js'
const J = (o) => ({ json: o })
describe('M-D04 jobs・schedules（ジョブキューと定期処理の記録）', () => {
  it('MT-D04-01 キューに入れる（種類ごとのやり直し回数）', async () => {
    const db = fakeDb({ rows: [{ job_id: 5 }] })
    expect(await jobs.enqueue('grading', { gradingId: 1 }, db)).toBe(5)
    expect(db.query.mock.calls[0][1]).toEqual({ kind: 'grading', payload: J({ gradingId: 1 }), maxAttempts: 1 })
    await jobs.enqueue('import', { importId: 2 }, db)
    expect(db.query.mock.calls[1][1].maxAttempts).toBe(3)
  })
  it('MT-D04-02 1件取り出す（ほかのワーカーと取り合わない）', async () => {
    const db = fakeDb({ rows: [{ job_id: 5, kind: 'import', payload: '{"importId":2}', attempts: 1, max_attempts: 3 }] })
    expect(await jobs.claimNext(['grading', 'import'], 60, db)).toEqual({ jobId: 5, kind: 'import', payload: { importId: 2 }, attempts: 1, maxAttempts: 3 })
    const [sql, params] = db.query.mock.calls[0]
    expect(sql).toContain('FOR UPDATE SKIP LOCKED')
    expect(sql).toContain("status = 'running' AND locked_until < now()")
    expect(params).toEqual({ kinds: 'grading,import', lockSeconds: 60 })
    expect(await jobs.claimNext(['grading'], 60, fakeDb({ rows: [{ job_id: 6, payload: { gradingId: 1 } }] }))).toMatchObject({ payload: { gradingId: 1 } })
    expect(await jobs.claimNext(['grading'], 60, fakeDb({ rows: [] }))).toBeNull()
  })
  it('MT-D04-03 完了・やり直し・失敗・数える・掃除', async () => {
    const db = fakeDb({ rows: [{ n: 2 }], updated: 4 })
    await jobs.complete(5, db)
    expect(db.execute.mock.calls[0]).toEqual([expect.stringContaining("status = 'done'"), { jobId: 5 }])
    await jobs.retry(5, 'x'.repeat(2000), 60, db)
    expect(db.execute.mock.calls[1][1]).toEqual({ jobId: 5, error: 'x'.repeat(1000), delaySeconds: 60 })
    await jobs.fail(5, new Error('boom'), db)
    expect(db.execute.mock.calls[2][1]).toEqual({ jobId: 5, error: 'Error: boom' })
    expect(await jobs.countFailedSince('2026-10-20T00:00:00+09:00', db)).toBe(2)
    expect(await jobs.deleteFinishedBefore('2026-09-20T00:00:00+09:00', db)).toBe(4)
  })
  it('MT-D04-04 定期処理の枠を取る・終える・放す', async () => {
    expect(await schedules.claim('daily', '2026-10-20', fakeDb({ rows: [{ name: 'daily' }] }))).toBe(true)
    const none = fakeDb({ rows: [] })
    expect(await schedules.claim('daily', '2026-10-20', none)).toBe(false)
    expect(none.query.mock.calls[0][0]).toContain('ON CONFLICT DO NOTHING')
    const db = fakeDb()
    await schedules.finish('daily', '2026-10-20', { ok: 1 }, db)
    expect(db.execute.mock.calls[0][1]).toEqual({ name: 'daily', slot: '2026-10-20', result: J({ ok: 1 }) })
    await schedules.release('mail', '2026-10-20T0730', db)
    expect(db.execute.mock.calls[1][0]).toContain('finished_at IS NULL')
  })
})
describe('M-D04 auth（ログインの記録）', () => {
  it('MT-D04-05 メールアドレスで探す（大文字小文字を区別しない）', async () => {
    const db = fakeDb({ rows: [{ user_id: 1, auth_sub: 's', password_hash: 'h', locked: false, roles: '["learner"]' }] })
    expect(await auth.findByEmail('A@x.jp', db)).toMatchObject({ userId: 1, authSub: 's', passwordHash: 'h', locked: false, roles: ['learner'] })
    expect(db.query.mock.calls[0][0]).toContain('lower(u.email) = lower(:email)')
    expect(await auth.findByEmail('a@x.jp', fakeDb({ rows: [] }))).toBeNull()
    expect(await auth.findById(1, fakeDb({ rows: [{ user_id: 1, roles: ['learner'] }] }))).toMatchObject({ roles: ['learner'] })
  })
  it('MT-D04-06 失敗の回数とロック', async () => {
    const db = fakeDb()
    await auth.recordFailure(1, db)
    expect(db.execute.mock.calls[0][0]).toContain(`failed_login_count + 1 >= ${auth.LOCK_AFTER_FAILURES}`)
    expect(db.execute.mock.calls[0][0]).toContain(`interval '${auth.LOCK_MINUTES} minutes'`)
    await auth.recordSuccess(1, db)
    expect(db.execute.mock.calls[1][0]).toContain('failed_login_count = 0, locked_until = NULL')
  })
  it('MT-D04-07 パスワードの保存と仮パスワードの期限', async () => {
    const db = fakeDb({ rows: [{ expired: true }] })
    await auth.setPassword(1, 'hash', { mustChange: true }, db)
    expect(db.execute.mock.calls[0][1]).toEqual({ userId: 1, hash: 'hash', mustChange: true, days: 7 })
    await auth.setPassword(1, 'hash', { mustChange: false, tempValidDays: 3 }, db)
    expect(db.execute.mock.calls[1][1].days).toBe(3)
    expect(await auth.tempPasswordExpired(1, db)).toBe(true)
    expect(await auth.tempPasswordExpired(1, fakeDb({ rows: [] }))).toBe(false)
  })
  it('MT-D04-08 リフレッシュトークン（保存・使い捨て・無効化）', async () => {
    const db = fakeDb({ rows: [{ user_id: 1 }] })
    await auth.saveRefreshToken('th', 1, 7, db)
    expect(db.execute.mock.calls[0][1]).toEqual({ tokenHash: 'th', userId: 1, days: 7 })
    expect(await auth.consumeRefreshToken('th', db)).toBe(1)
    expect(db.query.mock.calls[0][0]).toContain('revoked_at IS NULL AND expires_at > now()')
    expect(await auth.consumeRefreshToken('th', fakeDb({ rows: [] }))).toBeNull()
    await auth.revokeRefreshToken('th', db)
    await auth.revokeAllForUser(1, db)
    expect(db.execute.mock.calls.at(-1)[1]).toEqual({ userId: 1 })
  })
  it('MT-D04-09 再設定リンク（連打の防止・1回だけ使える）・掃除', async () => {
    expect(await auth.recentResetExists(1, 60, fakeDb({ rows: [{ '?column?': 1 }] }))).toBe(true)
    expect(await auth.recentResetExists(1, 60, fakeDb({ rows: [] }))).toBe(false)
    const db = fakeDb({ rows: [{ user_id: 1 }], updated: 2 })
    await auth.saveReset('th', 1, 60, db)
    expect(db.execute.mock.calls[0][1]).toEqual({ tokenHash: 'th', userId: 1, minutes: 60 })
    expect(await auth.consumeReset('th', db)).toBe(1)
    expect(await auth.consumeReset('th', fakeDb({ rows: [] }))).toBeNull()
    expect(await auth.deleteExpired(db)).toBe(4)
  })
})
