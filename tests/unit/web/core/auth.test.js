import { describe, it, expect, vi, beforeEach } from 'vitest'
import { createAuth, AuthError, TOKEN_KEY, REFRESH_BEFORE_MS } from '../../../../web/js/core/auth.js'
const config = { apiBase: '/api' }
const res = (status, body) => ({ ok: status < 400, status, json: async () => { if (body === undefined) throw new Error('no json'); return body } })
const tokens = (n = 1, expiresIn = 3600) => res(200, { idToken: `id${n}`, refreshToken: `r${n}`, expiresIn })
let fetchFn, showLogin, reload
const make = () => createAuth({ config, storage: window.sessionStorage, fetchFn, showLogin, reload })
const bodyOf = (i) => JSON.parse(fetchFn.mock.calls[i][1].body)
beforeEach(() => {
  sessionStorage.clear()
  fetchFn = vi.fn(async () => tokens())
  showLogin = vi.fn()
  reload = vi.fn()
})
describe('M-F01 core/auth', () => {
  it('MT-F01-01 ログインしていなければログイン画面', () => {
    const auth = make()
    expect(auth.ensureLogin()).toBe(false)
    expect(showLogin).toHaveBeenCalledTimes(1)
  })
  it('MT-F01-02 ログイン（A-30）でトークンを保存する', async () => {
    const auth = make()
    expect(await auth.signIn('a@x.jp', 'Pass1234')).toEqual({ done: true })
    expect(fetchFn.mock.calls[0][0]).toBe('/api/auth/login')
    expect(fetchFn.mock.calls[0][1]).toMatchObject({ method: 'POST', headers: { 'Content-Type': 'application/json' } })
    expect(bodyOf(0)).toEqual({ email: 'a@x.jp', password: 'Pass1234' })
    expect(await auth.getIdToken()).toBe('id1')
    expect(JSON.parse(sessionStorage.getItem(TOKEN_KEY))).toMatchObject({ idToken: 'id1', refreshToken: 'r1' })
    expect(localStorage.length).toBe(0)
  })
  it('MT-F01-03 仮パスワードのときは新しいパスワード（A-31）', async () => {
    fetchFn.mockResolvedValueOnce(res(200, { challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' }))
    const auth = make()
    expect(await auth.signIn('a@x.jp', 'Temp1234')).toEqual({ challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' })
    expect(await auth.getIdToken()).toBeNull()
    await auth.completeNewPassword('s1', 'Guild2026')
    expect(fetchFn.mock.calls[1][0]).toBe('/api/auth/new-password')
    expect(bodyOf(1)).toEqual({ session: 's1', newPassword: 'Guild2026' })
    expect(await auth.getIdToken()).toBe('id1')
  })
  it('MT-F01-04 失敗の応答', async () => {
    const auth = make()
    fetchFn.mockResolvedValueOnce(res(401, { error: { code: 'LOGIN_FAILED', message: '違います' } }))
    await expect(auth.signIn('a@x.jp', 'x')).rejects.toMatchObject({ name: 'AuthError', code: 'LOGIN_FAILED', status: 401, message: '違います' })
    fetchFn.mockResolvedValueOnce(res(502))
    await expect(auth.signIn('a@x.jp', 'x')).rejects.toMatchObject({ code: 'HTTP_502', status: 502 })
    fetchFn.mockRejectedValueOnce(new TypeError('offline'))
    await expect(auth.signIn('a@x.jp', 'x')).rejects.toMatchObject({ code: 'NETWORK', status: 0 })
    expect(new AuthError('X', 1).message).toBe('X')
  })
  it('MT-F01-05 保存済みのトークンでログイン済み', async () => {
    sessionStorage.setItem(TOKEN_KEY, JSON.stringify({ idToken: 'saved', refreshToken: 'r0', expiresAt: Date.now() + 3600000 }))
    const auth = make()
    expect(auth.ensureLogin()).toBe(true)
    expect(showLogin).not.toHaveBeenCalled()
    expect(await auth.getIdToken()).toBe('saved')
  })
  it('MT-F01-06 期限の5分前に更新（A-32、使い捨て）', async () => {
    vi.useFakeTimers()
    const auth = make()
    await auth.signIn('a@x.jp', 'Pass1234')
    fetchFn.mockResolvedValueOnce(tokens(2))
    await vi.advanceTimersByTimeAsync(3600 * 1000 - REFRESH_BEFORE_MS - 1)
    expect(fetchFn).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(fetchFn.mock.calls[1][0]).toBe('/api/auth/refresh')
    expect(bodyOf(1)).toEqual({ refreshToken: 'r1' })
    expect(await auth.getIdToken()).toBe('id2')
    expect(JSON.parse(sessionStorage.getItem(TOKEN_KEY)).refreshToken).toBe('r2')
  })
  it('MT-F01-07 更新の失敗はログイン画面からやり直す', async () => {
    const auth = make()
    await auth.signIn('a@x.jp', 'Pass1234')
    fetchFn.mockResolvedValueOnce(res(401, { error: { code: 'UNAUTHORIZED' } }))
    await expect(auth.refresh()).rejects.toMatchObject({ code: 'UNAUTHORIZED' })
    expect(sessionStorage.getItem(TOKEN_KEY)).toBeNull()
    expect(reload).toHaveBeenCalledTimes(1)
    await expect(make().refresh()).rejects.toThrow('no refresh token')
  })
  it('MT-F01-08 ログアウト（A-33）', async () => {
    const auth = make()
    await auth.signIn('a@x.jp', 'Pass1234')
    fetchFn.mockResolvedValueOnce(res(204))
    await auth.logout()
    expect(fetchFn.mock.calls[1][0]).toBe('/api/auth/logout')
    expect(bodyOf(1)).toEqual({ refreshToken: 'r1' })
    expect(sessionStorage.getItem(TOKEN_KEY)).toBeNull()
    expect(reload).toHaveBeenCalledTimes(1)
    // 通信できなくてもログアウトする・トークンがなければ API を呼ばない
    fetchFn.mockClear()
    await make().logout()
    expect(fetchFn).not.toHaveBeenCalled()
    const a2 = make()
    await a2.signIn('a@x.jp', 'Pass1234')
    fetchFn.mockRejectedValueOnce(new TypeError('offline'))
    await a2.logout()
    expect(reload).toHaveBeenCalledTimes(3)
  })
  it('MT-F01-09 login はトークンを消して読み込み直す・再設定（A-34・A-35）', async () => {
    const auth = make()
    await auth.signIn('a@x.jp', 'Pass1234')
    auth.login()
    expect(sessionStorage.getItem(TOKEN_KEY)).toBeNull()
    expect(reload).toHaveBeenCalledTimes(1)
    fetchFn.mockResolvedValueOnce(res(202, { status: 'accepted' }))
    expect(await auth.forgot('a@x.jp')).toEqual({ status: 'accepted' })
    expect(fetchFn.mock.calls.at(-1)[0]).toBe('/api/auth/forgot')
    fetchFn.mockResolvedValueOnce(res(204))
    expect(await auth.resetPassword('t1', 'Guild2026')).toBeNull()
    expect(JSON.parse(fetchFn.mock.calls.at(-1)[1].body)).toEqual({ token: 't1', newPassword: 'Guild2026' })
  })
  it('MT-F01-10 既定の apiBase と期限', async () => {
    const auth = createAuth({ config: {}, storage: window.sessionStorage, fetchFn: vi.fn(async () => res(200, { idToken: 'i', refreshToken: 'r' })), showLogin, reload })
    await auth.signIn('a@x.jp', 'p')
    expect(JSON.parse(sessionStorage.getItem(TOKEN_KEY)).expiresAt).toBeGreaterThan(Date.now() + 3500 * 1000)
  })
})
