import { describe, it, expect, vi, beforeEach } from 'vitest'
import { setContext } from '../../../../web/js/core/context.js'
import { createStore } from '../../../../web/js/core/store.js'
import { ApiError } from '../../../../web/js/core/api.js'
import * as onboarding from '../../../../web/js/pages/learner/onboarding.js'
const COURSES = { courses: [
  { id: 'c_1', name: 'AWS SAA', certification: 'AWS認定 ソリューションアーキテクト', questionCount: 120, coveragePct: 0, enrolled: false, current: false },
  { id: 'c_2', name: '基本情報', certification: '基本情報技術者', questionCount: 80, coveragePct: 12.5, enrolled: true, current: true, description: '午前の対策' }
] }
const NEW_USER = { needNickname: true, needCourse: true, needPartner: true }
let root, store, api, go
function setup(ob = NEW_USER, user = {}) {
  root = document.createElement('div')
  document.body.replaceChildren(root)
  store = createStore({ user: { roles: ['learner'], nickname: null, partner: null, ...user }, onboarding: { ...ob } })
  api = { apiGet: vi.fn(), apiPost: vi.fn(), apiPut: vi.fn() }
  go = vi.fn()
  setContext({ api, getState: store.getState, setState: store.setState, go })
}
const q = (sel) => root.querySelector(sel)
const click = (sel) => q(sel).dispatchEvent(new MouseEvent('click', { bubbles: true }))
const type = (sel, v) => { q(sel).value = v; q(sel).dispatchEvent(new Event('input')) }
const flush = () => new Promise((r) => setTimeout(r, 0))
beforeEach(() => setup())
describe('M-F09 初回の流れ', () => {
  it('MT-F09-01 済んでいればホームへ', async () => {
    setup({ needNickname: false, needCourse: false, needPartner: false })
    await onboarding.render(root)
    expect(go).toHaveBeenCalledWith('/home')
  })
  it('MT-F09-02 ステップ1：ニックネームの入力チェックと登録', async () => {
    await onboarding.render(root)
    expect(q('[aria-current="step"] .app-step-label').textContent).toBe('ニックネーム')
    expect(root.textContent).toContain('ステップ 1 / 3')
    const submit = q('[data-action="nickname"]')
    type('#nickname', 'あ')
    expect(q('#nickname-msg').textContent).toBe('ニックネームは2〜12文字で入力してください（いま1文字）')
    expect(submit.disabled).toBe(true)
    type('#nickname', 'たろう!')
    expect(q('#nickname-msg').textContent).toContain('使えるのは')
    type('#nickname', ' たろう ')
    expect(submit.disabled).toBe(false)
    api.apiPut.mockResolvedValue({ nickname: 'たろう' })
    api.apiGet.mockResolvedValue(COURSES)
    click('[data-action="nickname"]')
    await flush()
    expect(api.apiPut).toHaveBeenCalledWith('/me/profile', { nickname: 'たろう' })
    expect(store.getState().user.nickname).toBe('たろう')
    expect(q('[aria-current="step"] .app-step-label').textContent).toBe('コース')
  })
  it('MT-F09-03 ニックネームの重複（M-08）は責めずに知らせる', async () => {
    await onboarding.render(root)
    type('#nickname', 'たろう')
    api.apiPut.mockRejectedValue(new ApiError('CONFLICT', 409, { message: 'このニックネームはすでに使われています' }))
    click('[data-action="nickname"]')
    await flush()
    expect(q('[role="alert"]').textContent).toBe('このニックネームはすでに使われています')
    expect(q('[data-action="nickname"]').disabled).toBe(false)
  })
  it('MT-F09-04 ステップ2：コース一覧と受講中の印、選ぶと次へ', async () => {
    setup({ ...NEW_USER, needNickname: false }, { nickname: 'たろう' })
    api.apiGet.mockResolvedValue(COURSES)
    await onboarding.render(root)
    expect(api.apiGet).toHaveBeenCalledWith('/courses')
    const [done, now, todo] = root.querySelectorAll('.app-steps li')
    expect(done.className).toBe('app-step-done')
    expect(done.textContent).toBe('済ニックネーム（済み）')
    expect(now.querySelector('.app-step-no').textContent).toBe('2')
    expect(todo.className).toBe('app-step-todo')
    expect(root.querySelectorAll('.app-course')).toHaveLength(2)
    expect(root.querySelectorAll('.app-course')[1].textContent).toContain('受講中')
    expect(root.querySelectorAll('.app-course')[1].textContent).toContain('網羅率 12.5%')
    api.apiPost.mockResolvedValue({ courseId: 'c_1', enrolled: true })
    click('[data-course="c_1"]')
    await flush()
    expect(api.apiPost).toHaveBeenCalledWith('/enrollments', { courseId: 'c_1' })
    expect(store.getState().user.currentCourseId).toBe('c_1')
    expect(q('[aria-current="step"] .app-step-label').textContent).toBe('仲間')
  })
  it('MT-F09-05 コースの中でニックネームが重なったら、ニックネームの段階に戻して案内する', async () => {
    setup({ ...NEW_USER, needNickname: false }, { nickname: 'たろう' })
    api.apiGet.mockResolvedValue(COURSES)
    await onboarding.render(root)
    api.apiPost.mockRejectedValue(new ApiError('CONFLICT', 409))
    click('[data-course="c_1"]')
    await flush()
    expect(q('[aria-current="step"] .app-step-label').textContent).toBe('ニックネーム')
    expect(q('.app-notice').textContent).toBe(onboarding.NOTICE_NICKNAME_TAKEN)
    expect(q('#nickname').value).toBe('たろう')
    api.apiPut.mockResolvedValue({ nickname: 'たろう2' })
    type('#nickname', 'たろう2')
    click('[data-action="nickname"]')
    await flush()
    expect(q('[aria-current="step"] .app-step-label').textContent).toBe('コース')
    expect(store.getState().onboardingNotice).toBeNull()
  })
  it('MT-F09-06 コースを読み込めないときは再読み込みできる', async () => {
    setup({ ...NEW_USER, needNickname: false })
    api.apiGet.mockRejectedValueOnce(new ApiError('NETWORK', 0)).mockResolvedValue(COURSES)
    await onboarding.render(root)
    expect(q('[role="alert"]')).not.toBeNull()
    click('[data-action="reload"]')
    await flush()
    expect(root.querySelectorAll('.app-course')).toHaveLength(2)
  })
  it('MT-F09-07 ステップ3：仲間を選ぶまで押せず、名前を省くと初期名、決まったらホームへ', async () => {
    setup({ needNickname: false, needCourse: false, needPartner: true }, { nickname: 'たろう' })
    await onboarding.render(root)
    expect(root.querySelectorAll('[data-persona]')).toHaveLength(3)
    expect(q('[data-action="partner"]').disabled).toBe(true)
    click('[data-persona="logic"]')
    expect(q('[data-persona="logic"]').getAttribute('aria-checked')).toBe('true')
    expect(q('#partner-name').placeholder).toBe('セージ（初期名）')
    type('#partner-name', 'とても長い名前をつけてみた')
    expect(q('#partner-msg').textContent).toBe('名前は10文字以内で入力してください（いま13文字）')
    expect(q('[data-action="partner"]').disabled).toBe(true)
    type('#partner-name', '')
    api.apiPut.mockResolvedValue({ persona: 'logic', name: 'セージ' })
    click('[data-action="partner"]')
    await flush()
    expect(api.apiPut).toHaveBeenCalledWith('/me/partner', { persona: 'logic', name: '' })
    expect(store.getState().user.partner).toEqual({ persona: 'logic', name: 'セージ' })
    expect(store.getState().onboarding).toEqual({ needNickname: false, needCourse: false, needPartner: false })
    expect(go).toHaveBeenCalledWith('/home')
  })
})
