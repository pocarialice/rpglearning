import { describe, it, expect, vi, beforeEach } from 'vitest'
import { renderLogin, passwordOk, M_LOGIN_FAILED, M_FORGOT_SENT, M_RESET_DONE, M_RESET_INVALID, M_NETWORK } from '../../../../web/js/pages/login.js'
import { AuthError } from '../../../../web/js/core/auth.js'
let root, auth, win
function setup(hash = '') {
  root = document.createElement('div')
  document.body.replaceChildren(root)
  auth = { signIn: vi.fn(async () => ({ done: true })), completeNewPassword: vi.fn(async () => {}), forgot: vi.fn(async () => ({})), resetPassword: vi.fn(async () => null) }
  win = { location: { hash, pathname: '/', reload: vi.fn() }, history: { replaceState: vi.fn() } }
  renderLogin(root, { auth, win })
}
const q = (sel) => root.querySelector(sel)
const click = (sel) => q(sel).dispatchEvent(new MouseEvent('click', { bubbles: true }))
const type = (sel, v) => { q(sel).value = v; q(sel).dispatchEvent(new Event('input')) }
const flush = () => new Promise((r) => setTimeout(r, 0))
const errorText = () => q('.app-error')?.textContent
beforeEach(() => setup())
describe('M-F23 S-01 ログイン', () => {
  it('MT-F23-01 ログインして読み込み直す', async () => {
    expect(q('h1').textContent).toBe('RPG学習アプリ')
    expect(q('#login-email').getAttribute('autocomplete')).toBe('username')
    expect(q('#login-password').getAttribute('type')).toBe('password')
    type('#login-email', ' a@x.jp ')
    type('#login-password', 'Guild2026')
    click('[data-action="login"]')
    await flush()
    expect(auth.signIn).toHaveBeenCalledWith('a@x.jp', 'Guild2026')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-02 入力がない・失敗', async () => {
    click('[data-action="login"]')
    expect(errorText()).toBe(M_LOGIN_FAILED)
    expect(auth.signIn).not.toHaveBeenCalled()
    auth.signIn.mockRejectedValueOnce(new AuthError('LOGIN_FAILED', 401, 'メールアドレスかパスワードが正しくありません'))
    type('#login-email', 'a@x.jp')
    type('#login-password', 'x')
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe('メールアドレスかパスワードが正しくありません')
    expect(q('[data-action="login"]').disabled).toBe(false)
    auth.signIn.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
    auth.signIn.mockRejectedValueOnce(new AuthError('HTTP_502', 502))
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
  })
  it('MT-F23-03 初回は新しいパスワード（決まりを満たすまで押せない）', async () => {
    auth.signIn.mockResolvedValueOnce({ challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' })
    type('#login-email', 'a@x.jp')
    type('#login-password', 'Temp2345abcd')
    click('[data-action="login"]')
    await flush()
    expect(q('h1').textContent).toBe('新しいパスワード')
    const submit = q('[data-action="set-password"]')
    expect(submit.disabled).toBe(true)
    type('#new-password', 'guild2026')
    type('#new-password2', 'guild2026')
    expect(submit.disabled).toBe(true)
    type('#new-password', 'Guild2026')
    expect(submit.disabled).toBe(true)
    type('#new-password2', 'Guild2026')
    expect(submit.disabled).toBe(false)
    click('[data-action="set-password"]')
    await flush()
    expect(auth.completeNewPassword).toHaveBeenCalledWith('s1', 'Guild2026')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-04 新しいパスワードの失敗', async () => {
    auth.signIn.mockResolvedValueOnce({ challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' })
    type('#login-email', 'a@x.jp')
    type('#login-password', 'Temp2345abcd')
    click('[data-action="login"]')
    await flush()
    auth.completeNewPassword.mockRejectedValueOnce(new AuthError('UNAUTHORIZED', 401, '時間が経ちすぎました。もう一度ログインしてください'))
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe('時間が経ちすぎました。もう一度ログインしてください')
    expect(q('[data-action="set-password"]').disabled).toBe(false)
  })
  it('MT-F23-05 パスワードを忘れたとき（A-34）', async () => {
    click('[data-action="forgot"]')
    expect(q('h1').textContent).toBe('パスワードを忘れたとき')
    click('[data-action="send"]')
    expect(auth.forgot).not.toHaveBeenCalled()
    type('#forgot-email', 'a@x.jp')
    click('[data-action="send"]')
    await flush()
    expect(auth.forgot).toHaveBeenCalledWith('a@x.jp')
    expect(q('h1').textContent).toBe('RPG学習アプリ')
    expect(q('.app-notice').textContent).toBe(M_FORGOT_SENT)
    click('[data-action="forgot"]')
    auth.forgot.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    type('#forgot-email', 'a@x.jp')
    click('[data-action="send"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
    click('[data-action="back"]')
    expect(q('#login-email')).not.toBeNull()
  })
  it('MT-F23-06 再設定リンク（A-35）', async () => {
    setup('#/reset?token=t%2B1')
    expect(q('h1').textContent).toBe('パスワードの再設定')
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(auth.resetPassword).toHaveBeenCalledWith('t+1', 'Guild2026')
    expect(win.history.replaceState).toHaveBeenCalledWith(null, '', '/')
    expect(q('.app-notice').textContent).toBe(M_RESET_DONE)
  })
  it('MT-F23-07 期限切れの再設定リンク', async () => {
    setup('#/reset?token=old')
    auth.resetPassword.mockRejectedValueOnce(new AuthError('VALIDATION_ERROR', 400, 'x'))
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe(M_RESET_INVALID)
    auth.resetPassword.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
  })
  it('MT-F23-08 パスワードの決まり', () => {
    expect(passwordOk('Guild2026')).toBe(true)
    expect(passwordOk('Guild26')).toBe(false)
    expect(passwordOk('guild2026')).toBe(false)
    expect(passwordOk('GUILD2026')).toBe(false)
    expect(passwordOk('Guildguild')).toBe(false)
  })
})
