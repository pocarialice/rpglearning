import { describe, it, expect, vi, beforeEach } from 'vitest'
import { renderLogin, loadGsi, GSI_SRC, M_GOOGLE_FAILED, passwordOk, signupOk, M_LOGIN_FAILED, M_FORGOT_SENT, M_RESET_DONE, M_RESET_INVALID, M_NETWORK, M_SIGNUP_SENT, M_SIGNUP_INVALID, M_SIGNUP_VERIFYING } from '../../../../web/js/pages/login.js'
import { AuthError } from '../../../../web/js/core/auth.js'
let root, auth, win
function setup(hash = '', patch = () => {}) {
  root = document.createElement('div')
  document.body.replaceChildren(root)
  auth = { signIn: vi.fn(async () => ({ done: true })), completeNewPassword: vi.fn(async () => {}), forgot: vi.fn(async () => ({})), resetPassword: vi.fn(async () => null),
    signUp: vi.fn(async () => ({ status: 'accepted' })), verifySignup: vi.fn(async () => {}) }
  win = { location: { hash, pathname: '/', reload: vi.fn() }, history: { replaceState: vi.fn() } }
  patch(auth)
  renderLogin(root, { auth, win })
}
const q = (sel) => root.querySelector(sel)
const click = (sel) => q(sel).dispatchEvent(new MouseEvent('click', { bubbles: true }))
const type = (sel, v) => { q(sel).value = v; q(sel).dispatchEvent(new Event('input')) }
const flush = () => new Promise((r) => setTimeout(r, 0))
const errorText = () => q('.app-error')?.textContent
beforeEach(() => setup())
describe('M-F23 S-01 ログイン', () => {
  it('MT-F23-01 ログインして読み込み直す', async () => {
    expect(q('h1').textContent).toBe('RPG学習アプリ')
    expect(q('#login-email').getAttribute('autocomplete')).toBe('username')
    expect(q('#login-password').getAttribute('type')).toBe('password')
    type('#login-email', ' a@x.jp ')
    type('#login-password', 'Guild2026')
    click('[data-action="login"]')
    await flush()
    expect(auth.signIn).toHaveBeenCalledWith('a@x.jp', 'Guild2026')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-02 入力がない・失敗', async () => {
    click('[data-action="login"]')
    expect(errorText()).toBe(M_LOGIN_FAILED)
    expect(auth.signIn).not.toHaveBeenCalled()
    auth.signIn.mockRejectedValueOnce(new AuthError('LOGIN_FAILED', 401, 'メールアドレスかパスワードが正しくありません'))
    type('#login-email', 'a@x.jp')
    type('#login-password', 'x')
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe('メールアドレスかパスワードが正しくありません')
    expect(q('[data-action="login"]').disabled).toBe(false)
    auth.signIn.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
    auth.signIn.mockRejectedValueOnce(new AuthError('HTTP_502', 502))
    click('[data-action="login"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
  })
  it('MT-F23-03 初回は新しいパスワード（決まりを満たすまで押せない）', async () => {
    auth.signIn.mockResolvedValueOnce({ challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' })
    type('#login-email', 'a@x.jp')
    type('#login-password', 'Temp2345abcd')
    click('[data-action="login"]')
    await flush()
    expect(q('h1').textContent).toBe('新しいパスワード')
    const submit = q('[data-action="set-password"]')
    expect(submit.disabled).toBe(true)
    type('#new-password', 'guild2026')
    type('#new-password2', 'guild2026')
    expect(submit.disabled).toBe(true)
    type('#new-password', 'Guild2026')
    expect(submit.disabled).toBe(true)
    type('#new-password2', 'Guild2026')
    expect(submit.disabled).toBe(false)
    click('[data-action="set-password"]')
    await flush()
    expect(auth.completeNewPassword).toHaveBeenCalledWith('s1', 'Guild2026')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-04 新しいパスワードの失敗', async () => {
    auth.signIn.mockResolvedValueOnce({ challenge: 'NEW_PASSWORD_REQUIRED', session: 's1' })
    type('#login-email', 'a@x.jp')
    type('#login-password', 'Temp2345abcd')
    click('[data-action="login"]')
    await flush()
    auth.completeNewPassword.mockRejectedValueOnce(new AuthError('UNAUTHORIZED', 401, '時間が経ちすぎました。もう一度ログインしてください'))
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe('時間が経ちすぎました。もう一度ログインしてください')
    expect(q('[data-action="set-password"]').disabled).toBe(false)
  })
  it('MT-F23-05 パスワードを忘れたとき（A-34）', async () => {
    click('[data-action="forgot"]')
    expect(q('h1').textContent).toBe('パスワードを忘れたとき')
    click('[data-action="send"]')
    expect(auth.forgot).not.toHaveBeenCalled()
    type('#forgot-email', 'a@x.jp')
    click('[data-action="send"]')
    await flush()
    expect(auth.forgot).toHaveBeenCalledWith('a@x.jp')
    expect(q('h1').textContent).toBe('RPG学習アプリ')
    expect(q('.app-notice').textContent).toBe(M_FORGOT_SENT)
    click('[data-action="forgot"]')
    auth.forgot.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    type('#forgot-email', 'a@x.jp')
    click('[data-action="send"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
    click('[data-action="back"]')
    expect(q('#login-email')).not.toBeNull()
  })
  it('MT-F23-06 再設定リンク（A-35）', async () => {
    setup('#/reset?token=t%2B1')
    expect(q('h1').textContent).toBe('パスワードの再設定')
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(auth.resetPassword).toHaveBeenCalledWith('t+1', 'Guild2026')
    expect(win.history.replaceState).toHaveBeenCalledWith(null, '', '/')
    expect(q('.app-notice').textContent).toBe(M_RESET_DONE)
  })
  it('MT-F23-07 期限切れの再設定リンク', async () => {
    setup('#/reset?token=old')
    auth.resetPassword.mockRejectedValueOnce(new AuthError('VALIDATION_ERROR', 400, 'x'))
    type('#new-password', 'Guild2026')
    type('#new-password2', 'Guild2026')
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe(M_RESET_INVALID)
    auth.resetPassword.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    click('[data-action="set-password"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
  })
  it('MT-F23-08 パスワードの決まり', () => {
    expect(passwordOk('Guild2026')).toBe(true)
    expect(passwordOk('Guild26')).toBe(false)
    expect(passwordOk('guild2026')).toBe(false)
    expect(passwordOk('GUILD2026')).toBe(false)
    expect(passwordOk('Guildguild')).toBe(false)
  })
  it('MT-F23-09 ログイン画面からアカウントを作る（A-36）', async () => {
    click('[data-action="signup"]')
    expect(q('h1').textContent).toBe('アカウントを作る')
    expect(q('#signup-email').getAttribute('autocomplete')).toBe('email')
    expect(q('#signup-password').getAttribute('autocomplete')).toBe('new-password')
    const submit = q('[data-action="signup-send"]')
    expect(submit.disabled).toBe(true)
    type('#signup-name', ' 山田 花子 ')
    type('#signup-email', 'hana@x.jp')
    type('#signup-password', 'Guild2026')
    expect(submit.disabled).toBe(true)
    type('#signup-password2', 'Guild2027')
    expect(submit.disabled).toBe(true)
    type('#signup-password2', 'Guild2026')
    expect(submit.disabled).toBe(false)
    click('[data-action="signup-send"]')
    await flush()
    expect(auth.signUp).toHaveBeenCalledWith('hana@x.jp', '山田 花子', 'Guild2026')
    expect(q('h1').textContent).toBe('RPG学習アプリ')
    expect(q('.app-notice').textContent).toBe(M_SIGNUP_SENT)
  })
  it('MT-F23-10 アカウント作成の失敗と戻る', async () => {
    click('[data-action="signup"]')
    type('#signup-name', '花子')
    type('#signup-email', 'hana@x.jp')
    type('#signup-password', 'Guild2026')
    type('#signup-password2', 'Guild2026')
    auth.signUp.mockRejectedValueOnce(new AuthError('VALIDATION_ERROR', 400, '入力内容に誤りがあります'))
    click('[data-action="signup-send"]')
    await flush()
    expect(errorText()).toBe('入力内容に誤りがあります')
    expect(q('[data-action="signup-send"]').disabled).toBe(false)
    auth.signUp.mockRejectedValueOnce(new AuthError('NETWORK', 0))
    click('[data-action="signup-send"]')
    await flush()
    expect(errorText()).toBe(M_NETWORK)
    click('[data-action="back"]')
    expect(q('#login-email')).not.toBeNull()
  })
  it('MT-F23-11 確認リンク（A-37）で登録してログインする', async () => {
    let done
    setup('#/signup?token=t%2B1', (a) => a.verifySignup.mockImplementationOnce(() => new Promise((r) => { done = r })))
    expect(q('h1').textContent).toBe('アカウントの登録')
    expect(q('[role="status"]').textContent).toBe(M_SIGNUP_VERIFYING)
    expect(auth.verifySignup).toHaveBeenCalledWith('t+1')
    done()
    await flush()
    expect(win.history.replaceState).toHaveBeenCalledWith(null, '', '/')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-12 期限切れの確認リンク・登録済み', async () => {
    setup('#/signup?token=old', (a) => a.verifySignup.mockRejectedValueOnce(new AuthError('VALIDATION_ERROR', 400, 'x')))
    await flush()
    expect(errorText()).toBe(M_SIGNUP_INVALID)
    expect(win.location.reload).not.toHaveBeenCalled()
    click('[data-action="back"]')
    expect(win.history.replaceState).toHaveBeenCalledWith(null, '', '/')
    expect(q('#login-email')).not.toBeNull()
    setup('#/signup?token=t', (a) => a.verifySignup.mockRejectedValueOnce(new AuthError('CONFLICT', 409, 'このメールアドレスはすでに登録されています。ログイン画面からログインしてください')))
    await flush()
    expect(errorText()).toBe('このメールアドレスはすでに登録されています。ログイン画面からログインしてください')
  })
  it('MT-F23-13 アカウント作成の入力の決まり', () => {
    const v = { fullName: '花子', email: 'a@x.jp', password: 'Guild2026', password2: 'Guild2026' }
    expect(signupOk(v)).toBe(true)
    expect(signupOk({ ...v, fullName: ' ' })).toBe(false)
    expect(signupOk({ ...v, fullName: 'あ'.repeat(51) })).toBe(false)
    expect(signupOk({ ...v, email: 'a@x' })).toBe(false)
    expect(signupOk({ ...v, password: 'guild2026', password2: 'guild2026' })).toBe(false)
    expect(signupOk({ ...v, password2: 'Guild2027' })).toBe(false)
  })
})
describe('M-F23 S-01 Googleでログイン', () => {
  let gsi, cb
  function setupGoogle({ clientId = 'cid', google = true } = {}) {
    root = document.createElement('div')
    document.body.replaceChildren(root)
    gsi = { initialize: vi.fn((o) => { cb = o.callback }), renderButton: vi.fn() }
    auth = { signIn: vi.fn(), googleConfig: vi.fn(async () => ({ clientId })), signInWithGoogle: vi.fn(async () => {}) }
    win = { location: { hash: '', pathname: '/', reload: vi.fn() }, history: { replaceState: vi.fn() }, document }
    if (google) win.google = { accounts: { id: gsi } }
    renderLogin(root, { auth, win })
  }
  it('MT-F23-14 クライアントIDがあればボタンを出し、押したらログインして読み込み直す', async () => {
    setupGoogle()
    await flush()
    expect(q('.app-google').hidden).toBe(false)
    expect(gsi.initialize).toHaveBeenCalledWith(expect.objectContaining({ client_id: 'cid' }))
    expect(gsi.renderButton.mock.calls[0][0]).toBe(q('.app-google-button'))
    await cb({ credential: 'cred' })
    expect(auth.signInWithGoogle).toHaveBeenCalledWith('cred')
    expect(win.location.reload).toHaveBeenCalledTimes(1)
  })
  it('MT-F23-15 失敗したらメッセージを出す', async () => {
    setupGoogle()
    await flush()
    auth.signInWithGoogle.mockRejectedValueOnce(new AuthError('LOGIN_FAILED', 401))
    await cb({ credential: 'x' })
    expect(errorText()).toBe(M_GOOGLE_FAILED)
    auth.signInWithGoogle.mockRejectedValueOnce(new AuthError('NETWORK', 0, 'offline'))
    await cb({})
    expect(errorText()).toBe(M_NETWORK)
    auth.signInWithGoogle.mockRejectedValueOnce(new AuthError('CONFLICT', 409, 'このメールアドレスは別のGoogleアカウントと結びついています'))
    await cb({ credential: 'x' })
    expect(errorText()).toBe('このメールアドレスは別のGoogleアカウントと結びついています')
    expect(win.location.reload).not.toHaveBeenCalled()
  })
  it('MT-F23-16 クライアントIDがない・設定を読めないときはボタンを出さない', async () => {
    setupGoogle({ clientId: null })
    await flush()
    expect(q('.app-google').hidden).toBe(true)
    expect(gsi.initialize).not.toHaveBeenCalled()
    setupGoogle()
    auth.googleConfig.mockRejectedValueOnce(new Error('x'))
    renderLogin(root, { auth, win })
    await flush()
    expect(q('.app-google').hidden).toBe(true)
  })
  it('MT-F23-17 Google のスクリプトを1回だけ読み込む', async () => {
    setupGoogle({ google: false })
    await flush()
    const script = document.head.querySelector(`script[src="${GSI_SRC}"]`)
    expect(script.async).toBe(true)
    const again = loadGsi(win)
    expect(document.head.querySelectorAll(`script[src="${GSI_SRC}"]`)).toHaveLength(1)
    win.google = { accounts: { id: gsi } }
    script.onload()
    await again
    await flush()
    expect(gsi.renderButton).toHaveBeenCalledTimes(1)
    // 読み込めなければボタンを出さず、次はもう一度読み込む
    const w2 = { document }
    const p = loadGsi(w2)
    document.head.lastElementChild.onerror()
    await expect(p).rejects.toThrow('gsi load failed')
    expect(w2.__gsiLoading).toBeNull()
  })
  it('MT-F23-18 ほかの画面に移ったあとはボタンを出さない', async () => {
    setupGoogle()
    root.remove()
    await flush()
    expect(gsi.renderButton).not.toHaveBeenCalled()
  })
})
