describe('S-14 AIパートナー設定', () => {
  const P = (persona, label, defaultName, imageUrl = null) => ({ persona, label, defaultName, imageUrl })
  const route = () => api.apiGet.mockImplementation(async (p) => ({
    '/admin/partners/encourage/image': P('encourage', '励まし型', 'ミナ', 'https://app/partners/encourage-1.png'),
    '/admin/partners/logic/image': P('logic', '論理型', 'セージ'),
    '/admin/partners/rival/image': P('rival', 'ライバル型', 'レン')
  })[p])
  const pick = (persona, file) => {
    const input = q(`[data-persona-card="${persona}"] [data-file]`)
    Object.defineProperty(input, 'files', { value: [file], configurable: true })
    input.dispatchEvent(new Event('change', { bubbles: true }))
  }
  beforeEach(() => {
    URL.createObjectURL = vi.fn(() => 'blob:preview')
    URL.revokeObjectURL = vi.fn()
  })
  it('3人の性格名・初期名・今の画像と見本', async () => {
    route()
    await partnersPage.render(root)
    const cards = root.querySelectorAll('[data-persona-card]')
    expect(cards).toHaveLength(3)
    expect(cards[0].textContent).toContain('励まし型・初期名 ミナ')
    expect(cards[0].querySelector('.app-sigil-img').getAttribute('src')).toBe('https://app/partners/encourage-1.png')
    expect(cards[1].querySelector('.app-sigil-img')).toBeNull()
    expect(cards[1].querySelector('.gd-sigil').textContent).toBe('セ')
    expect(cards[0].querySelector('[data-action="remove"]')).not.toBeNull()
    expect(cards[1].querySelector('[data-action="remove"]')).toBeNull()
  })
  it('種類・大きさの確認とプレビュー', async () => {
    route()
    await partnersPage.render(root)
    pick('logic', new File(['x'], 'a.jpg', { type: 'image/jpeg' }))
    expect(q('[data-persona-card="logic"] [data-msg]').textContent).toBe('PNG か WebP の画像を選んでください')
    expect(q('[data-persona-card="logic"] [data-action="replace"]').disabled).toBe(true)
    const big = new File(['x'], 'b.png', { type: 'image/png' })
    Object.defineProperty(big, 'size', { value: 3 * 1024 * 1024 })
    pick('logic', big)
    expect(q('[data-persona-card="logic"] [data-msg]').textContent).toBe('画像は2MBまでにしてください')
    pick('logic', new File(['png'], 'c.png', { type: 'image/png' }))
    expect(q('[data-persona-card="logic"]').textContent).toContain('（プレビュー）')
    expect(q('[data-persona-card="logic"] .app-sigil-img').getAttribute('src')).toBe('blob:preview')
    expect(q('[data-persona-card="logic"] [data-action="replace"]').disabled).toBe(false)
  })
  it('差し替える：prepare → S3 へ PUT → commit', async () => {
    route()
    await partnersPage.render(root)
    const file = new File(['png'], 'c.png', { type: 'image/png' })
    pick('logic', file)
    api.apiPut.mockResolvedValueOnce({ imageKey: 'partners/logic-20261021120000.png', uploadUrl: 'https://s3/put' }).mockResolvedValueOnce({ persona: 'logic', imageUrl: 'https://app/partners/logic-20261021120000.png' })
    globalThis.fetch = vi.fn(async () => ({ ok: true, status: 200 }))
    click('[data-persona-card="logic"] [data-action="replace"]')
    await flush()
    await flush()
    expect(api.apiPut).toHaveBeenNthCalledWith(1, '/admin/partners/logic/image', { action: 'prepare', contentType: 'image/png', size: 3 })
    expect(globalThis.fetch).toHaveBeenCalledWith('https://s3/put', { method: 'PUT', headers: { 'Content-Type': 'image/png' }, body: file })
    expect(api.apiPut).toHaveBeenNthCalledWith(2, '/admin/partners/logic/image', { action: 'commit', imageKey: 'partners/logic-20261021120000.png' })
    expect(q('[data-persona-card="logic"] .app-sigil-img').getAttribute('src')).toBe('https://app/partners/logic-20261021120000.png')
    expect(q('[data-persona-card="logic"]').textContent).toContain('差し替えた')
    expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:preview')
  })
  it('アップロードに失敗したら確定しない', async () => {
    route()
    await partnersPage.render(root)
    pick('logic', new File(['png'], 'c.png', { type: 'image/png' }))
    api.apiPut.mockResolvedValueOnce({ imageKey: 'k', uploadUrl: 'https://s3/put' })
    globalThis.fetch = vi.fn(async () => ({ ok: false, status: 403 }))
    click('[data-persona-card="logic"] [data-action="replace"]')
    await flush()
    await flush()
    expect(api.apiPut).toHaveBeenCalledTimes(1)
    expect(q('[data-persona-card="logic"] [role="alert"]').textContent).toBe(partnersPage.M_IMAGE_ERROR)
  })
  it('画像を外す（確認ダイアログ）', async () => {
    route()
    await partnersPage.render(root)
    click('[data-persona-card="encourage"] [data-action="remove"]')
    expect(q('dialog').textContent).toContain('名前の頭文字の表示に戻ります')
    api.apiDelete.mockResolvedValue({ persona: 'encourage', imageUrl: null })
    click('dialog [data-action="confirm"]')
    await flush()
    expect(api.apiDelete).toHaveBeenCalledWith('/admin/partners/encourage/image')
    expect(q('dialog')).toBeNull()
    expect(q('[data-persona-card="encourage"] .app-sigil-img')).toBeNull()
    expect(q('[data-persona-card="encourage"]').textContent).toContain('画像を外した')
  })
  it('読み込めないときは再読み込みできる', async () => {
    api.apiGet.mockRejectedValueOnce(new ApiError('NETWORK', 0))
    await partnersPage.render(root)
    route()
    click('[data-action="reload"]')
    await flush()
    expect(root.querySelectorAll('[data-persona-card]')).toHaveLength(3)
  })
})
